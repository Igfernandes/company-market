    </h4>
</div>
<div class="text">
    A CONTROLADORA não compartilhará os dados pessoais do TITULAR com outros agentes de tratamento de dados
    (nacionais ou internacionais), salvo seja necessário para as finalidades listadas neste termo, observando o
    princípio e as garantias estabelecidas pela Lei nº13.709.
</div>
<div class="title">
    <h4>
        <strong>
            Segurança dos dados:
        </strong>
    </h4>
</div>
<div class="text">
    <p>
        A Controladora responsabiliza-se pela manutenção de medidas de segurança, técnicas e administrativas
        aptas a proteger os dados pessoais de acessos não autorizados e de situações acidentais ou ilícitas de
        destruição, perda, alteração, comunicação ou qualquer forma de tratamento inadequado ou ilícito. A
        Controladora fica responsável por comunicar ao Titular e a Autoridade Nacional de Proteção de dados a
        ocorrência de eventuais incidentes de segurança que possam acarretar riscos ou danos ao Titular como
        estabelece o artigo 48 da lei 13.709 de 2018.
    </p>
</div>

<div class="title">
    <h4>
        <strong>
            Direitos do Titular:
        </strong>
    </h4>
</div>
<div class="text">
    <p>
        O Titular tem direito a obter da Controladora, em relação aos dados por ela tratados, a qualquer momento
        mediante requisição, I- acesso aos dados; II- correção de dados incompletos, inexatos ou desatualizados;
        III- anonimização, bloqueio, ou eliminação de dados desnecessários, excessivos, ou tratados em
        desconformidade com o disposto na Lei nº13.709; IV- revogação do consentimento, nos termos do §5º do
        art. 8º da Lei nº13.709.
    </p>
</div>
<div class="title">
    <h4>
        <strong>
            Término do tratamento de dados:
        </strong>
    </h4>
</div>
<div class="text">
