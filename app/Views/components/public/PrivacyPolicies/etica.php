<div class="title">
    <h5>
        <strong>
            Dos Fundamentos Éticos
        </strong>
    </h5>
</div>
<div class="text">
    <p>
        Art. 1⁰ - O Código de Ética da Confederação Brasileira de Tiro com Arco define os princípios de conduta
        que devem pautar as atividades esportivas e administrativas da entidade e da comunidade do Tiro com Arco
        no país.
    </p>
</div>
<div class="text">
    <p>
        ART. 2⁰ - As regras magnas contidas no Código expressam os valores e princípios da CBTARCO como entidade
        máxima de representação do Tiro com Arco no Brasil, das suas federações, ligas e dos Clubes a essas
        filiadas, assim como todos os profissionais ligados a modalidade (árbitros, instrutores e técnicos).
    </p>
</div>
<div class="text">
    <p>
        Art. 3⁰ O Código tem o objetivo de enfatizar os ideais de dignidade, integridade, o espírito de
        cooperação e congraçamento e, principalmente, de esportividade e competição justa que devem caracterizar
        a conduta de todos os que fazem parte da comunidade do Tiro com Arco no País.
    </p>
</div>
<div class="text">
    <p>
        Art. 4⁰ Os membros da comunidade do Tiro com Arco no Brasil, da qual fazem parte dirigentes, árbitros,
        atletas, técnicos, colaboradores, quer da CBTARCO quer das federações estaduais e do DF e todos que
        direta ou indiretamente dela participem e influenciem, assumem o compromisso de pautar seus
        comportamentos, condutas e atitudes de acordo com os seguintes princípios éticos:
    </p>
</div>
<div class="ordenad-list">
    <ol>
        <li>- cumprir e zelar pelo cumprimento do Estatuto da Confederação Brasileira de Tiro com Arco,
            reconhecendo, apoiando e divulgando os objetivos, valores, princípios e políticas da entidade.</li>
        <li>– conhecer, cumprir e zelar pelas regras, normas e regulamentos que disciplinam a prática do Tiro
            com Arco e divulgá-las, tanto no âmbito nacional quanto internacional.</li>
        <li>- respeitar, estimular e implementar a participação competitiva justa e, com ela, tanto a prática do
            desporto quanto a conquista da vitória, como reconhecimento do melhor desempenho, e de seu
            aprimoramento obedecendo, rigorosamente, as regras, normas e regulamentos do Tiro com Arco sempre
            entendendo que competir já é uma vitória por si só e atuar de forma exemplar está acima de vencer.
        </li>
