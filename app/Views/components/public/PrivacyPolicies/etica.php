            atletas, treinadores, competidores, colaboradores e ao público em geral, de modo a fazer prevalecer
            os princípios da justiça, do direito, da esportividade e a competição justa.</li>
        <li>- Defender a permanente valorização do Tiro com Arco, tendo em vista a divulgação de sua prática,
            seu aprimoramento técnico e melhor desempenho esportivo dentro dos melhores princípios de
            fraternidade e congraçamento dos atletas, aficionados e das entidades congêneres, no País e no
            mundo.</li>
        <li>– Observar, acatar e cumprir com seriedade as diretivas e sanções aplicadas dentro do espírito das
            leis, normas, regulamentos disciplinares e dos usos e costumes da modalidade esportiva do Tiro com
            Arco.</li>
        <li>- Reprimir a violência física e psicológica no esporte e valorizar a competição justa e o espírito
            esportivo, em todas as ocasiões e suas formas de manifestação.</li>
        <li>- Prevenir, desencorajar e denunciar quaisquer preconceitos e preferências, em todos os tipos de
            competições e modalidades do Tiro com Arco, com origem nas diferenças étnicas, de cor, gênero,
            crença religiosa, portadores de deficiência, preferência política, condição financeira, social,
            intelectual, opção sexual, idade, condição marital, entre outras formas de exclusão social e
            estimular o respeito aos símbolos nacionais e à confraternização entre as nações e o respeito à
            humanidade, em geral.</li>
        <li>- Coibir, impedir e denunciar o uso de qualquer tipo de droga ou estimulantes químicos
            desautorizados, de modo a preservar o princípio universal da igualdade de oportunidades e da
            integridade física e mental do indivíduo.</li>
        <li>Rejeitar, rechaçar e denunciar qualquer forma de favorecimento desleal e de corrupção, de que
            natureza for assegurando a probidade e a dignidade no âmbito do esporte e desestimulando sua
            mercantilização.</li>
