    <h4>
        <strong>
            CÓDIGO DE ÉTICA
        </strong>
    </h4>
</div>
<div class="text">
    <p>
        O código de ética de uma confederação esportiva visa reger direcionamento básico baseado em aspectos
        legais, valores éticos em desenvolvimento com a sociedade Brasileira. O objetivo, em longo prazo, é não
        só atingir os patamares mais elevados do esporte mundial, mas sim colaborar com o avanço futuro nos
        moldes éticos mundiais para a modalidade.
    </p>
</div>

<div class="text">
    <p>
        Nesse sentido, cumpre-nos ressaltar a importância da pronta e perfeita aplicação do presente Código,
        cujas normas expressam procedimentos éticos, morais e técnicos que marcam o Tiro com Arco, como esporte,
        entidade e agente de formação e desenvolvimento desse desporto de tanta aceitação e valor para o
        desenvolvimento atlético e social do País, contribuindo, destarte, para a elevação crescente de nosso
        prestígio internacional.
    </p>
</div>
<div class="text">
    <p>
        Este documento representa fonte perene de inspiração a cada um e a todos os esportistas ligados à
        CBTARCO, para honra maior do esporte e permanente engrandecimento da nossa Pátria, com a concordância de
        todos os órgãos da estrutura oficial do Tiro com Arco no Brasil, congregando pessoas jurídicas e
        físicas, vinculadas formalmente as suas três instâncias organizacionais, Confederação Brasileira de Tiro
        com Arco, Federações Estaduais e Clubes.
    </p>
</div>
<div class="text">
    <p>
        Rio de Janeiro, 25 de julho de 2020
    </p>
</div>

